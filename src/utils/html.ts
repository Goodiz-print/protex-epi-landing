/** Échappe une valeur interpolée dans du HTML construit côté client
 * (texte ou attribut entre guillemets doubles). */
export function escapeHtml(value: string): string {
	return value
		.replaceAll('&', '&amp;')
		.replaceAll('<', '&lt;')
		.replaceAll('>', '&gt;')
		.replaceAll('"', '&quot;')
		.replaceAll("'", '&#39;');
}
