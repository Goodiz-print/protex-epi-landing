#!/usr/bin/env node
// Resolves the raw supplier exports into the catalog data the site actually builds from.
//
// The site only ever needs the ~14 fields of the `Product` schema per product card.
// The supplier exports it is derived from are two orders of magnitude bigger (~68 MB of
// CSV across Portwest, Mascot and Blaklader) and are re-parsed and re-joined on every
// `astro dev`/`astro build` even though their result only changes when a supplier ships
// a new export. This script does that work once, manually, and writes a compact JSON per
// supplier — `src/data/catalog/products.<supplier>.json` — which is what
// `src/content.config.ts` loads (see `src/content/loaders/json-products-loader.ts`).
//
// The raw CSVs are gitignored: only these JSON files are committed.
//
// Run manually: `node scripts/generate-catalog-data.mjs [--supplier portwest,mascot]`
// Never run by astro dev/build. Rerun after any new supplier export.
//
// A supplier whose export is missing from src/data/suppliers/<supplier>/ is skipped and its
// committed catalog JSON is left as is, so the script can run on a machine that only has one
// supplier's files. The manual fixes are re-applied on top of the export: category overrides
// (already merged into category-mapping.<supplier>.json by reclassify-catalog.mjs) and image
// overrides (src/data/image-overrides.<supplier>.json), after naming the rows the export left
// blank (scripts/lib/complete-products.mjs + src/data/product-overrides.<supplier>.json).
//
// The grouping/joining/mapping logic is NOT duplicated here: it is imported from
// `scripts/lib/supplier-csv.ts`, the single source of truth
// (Node strips the TypeScript types at import time).

import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'csv-parse/sync';
import {
	buildBlakladerColourIndex,
	buildBlakladerMediaIndex,
	buildBlakladerProductEntry,
	buildMascotEntry,
	buildProductEntry,
	groupBlakladerRows,
	groupMascotRows,
	groupPortwestRows,
} from './lib/supplier-csv.ts';
import { applyImageOverrides, readImageOverrides } from './lib/image-overrides.mjs';
import { completeProducts, readProductOverrides } from './lib/complete-products.mjs';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');
const OUT_DIR = resolve(ROOT, 'src/data/catalog');

// Same shape as the old `csvProductsLoader` sources: this is where the supplier → file
// wiring now lives, since `content.config.ts` only knows about the generated JSON.
const SOURCES = [
	{
		supplier: 'portwest',
		csvPath: 'src/data/suppliers/portwest/product_sheet_FR_A8_20.csv',
		mappingPath: 'src/data/category-mapping.portwest.json',
		// Regenerated by scripts/check-product-images.mjs; URLs confirmed dead by a live HTTP check.
		knownBadImagesPath: 'src/data/known-bad-images.portwest.json',
	},
	{
		supplier: 'mascot',
		// Slim CSV produced by scripts/prepare-mascot-csv.mjs (semicolon-delimited).
		csvPath: 'src/data/suppliers/mascot/mascot-products.slim.csv',
		mappingPath: 'src/data/category-mapping.mascot.json',
	},
	{
		supplier: 'blaklader',
		commercePath: 'src/data/suppliers/blaklader/Blaklader - FAB-DIS 3.0 - 2026.xlsm - B01_COMMERCE.csv',
		variantePath: 'src/data/suppliers/blaklader/Blaklader - FAB-DIS 3.0 - 2026.xlsm - C03_VARIANTE.csv',
		mediaPath: 'src/data/suppliers/blaklader/Blaklader - FAB-DIS 3.0 - 2026.xlsm - B03_MEDIA.csv',
		mappingPath: 'src/data/category-mapping.blaklader.json',
	},
];

function readCsv(absPath, delimiter = ',') {
	const content = readFileSync(absPath, 'utf-8');
	return parse(content, {
		columns: true,
		bom: true,
		trim: true,
		skip_empty_lines: true,
		delimiter,
	});
}

function readMapping(source) {
	return JSON.parse(readFileSync(resolve(ROOT, source.mappingPath), 'utf-8'));
}

/** One product per line inside a JSON array: compact enough, still diffable in git. */
function writeCatalog(supplier, products) {
	mkdirSync(OUT_DIR, { recursive: true });
	const outPath = resolve(OUT_DIR, `products.${supplier}.json`);
	const body = products.map((product) => JSON.stringify(product)).join(',\n');
	writeFileSync(outPath, `[\n${body}\n]\n`, 'utf-8');
	return outPath;
}

function buildPortwest(source) {
	const csvAbsPath = resolve(ROOT, source.csvPath);
	const mapping = readMapping(source);
	const rows = readCsv(csvAbsPath);
	const groups = groupPortwestRows(rows);
	const knownBadImageUrls = new Set(JSON.parse(readFileSync(resolve(ROOT, source.knownBadImagesPath), 'utf-8')));

	const products = [];
	const warnings = [];
	for (const group of groups) {
		const result = buildProductEntry(source.supplier, group, mapping, knownBadImageUrls);
		warnings.push(...result.warnings);
		products.push(result.data);
	}

	return { products, warnings, summary: `${products.length} products from ${rows.length} CSV rows` };
}

function buildMascot(source) {
	const csvAbsPath = resolve(ROOT, source.csvPath);
	const mapping = readMapping(source);
	const rows = readCsv(csvAbsPath, ';');
	const groups = groupMascotRows(rows);

	const products = [];
	const warnings = [];
	for (const group of groups) {
		const result = buildMascotEntry(group, mapping);
		warnings.push(...result.warnings);
		if (result.data) {
			products.push(result.data);
		}
	}

	return {
		products,
		warnings,
		summary: `${products.length} products from ${groups.length} groups / ${rows.length} CSV rows`,
	};
}

function buildBlaklader(source) {
	const commerceAbsPath = resolve(ROOT, source.commercePath);
	const mapping = readMapping(source);
	const commerceRows = readCsv(commerceAbsPath);
	const colourIndex = buildBlakladerColourIndex(readCsv(resolve(ROOT, source.variantePath)));
	const mediaIndex = buildBlakladerMediaIndex(readCsv(resolve(ROOT, source.mediaPath)));
	const groups = groupBlakladerRows(commerceRows);

	const products = [];
	const warnings = [];
	for (const group of groups) {
		const result = buildBlakladerProductEntry(group, colourIndex, mediaIndex, mapping);
		warnings.push(...result.warnings);
		if (result.data) {
			products.push(result.data);
		}
	}

	return {
		products,
		warnings,
		summary: `${products.length} products from ${groups.length} groups / ${commerceRows.length} CSV rows`,
	};
}

const BUILDERS = {
	portwest: buildPortwest,
	mascot: buildMascot,
	blaklader: buildBlaklader,
};

/** Every raw file this source reads, relative to the project root. */
function exportFiles(source) {
	return [source.csvPath, source.commercePath, source.variantePath, source.mediaPath].filter(Boolean);
}

function parseSuppliers(argv) {
	const index = argv.indexOf('--supplier');
	if (index === -1) return SOURCES.map((source) => source.supplier);
	const wanted = (argv[index + 1] ?? '').split(',').map((value) => value.trim());
	for (const supplier of wanted) {
		if (!SOURCES.some((source) => source.supplier === supplier)) {
			console.error(`Unknown supplier ${supplier}`);
			process.exit(1);
		}
	}
	return wanted;
}

function main() {
	const suppliers = parseSuppliers(process.argv.slice(2));
	let totalProducts = 0;
	let totalWarnings = 0;

	for (const source of SOURCES) {
		if (!suppliers.includes(source.supplier)) continue;
		const missing = exportFiles(source).filter((path) => !existsSync(resolve(ROOT, path)));
		if (missing.length > 0) {
			console.log(
				`[${source.supplier}] export not found (${missing.join(', ')}) — keeping the committed src/data/catalog/products.${source.supplier}.json`,
			);
			continue;
		}
		const built = BUILDERS[source.supplier](source);
		const { warnings, summary } = built;
		// Names for the rows the export leaves blank (src/data/product-overrides.<supplier>.json
		// + sibling colourways). Before the image overrides, which are keyed by the final id.
		const { products, report } = completeProducts(
			source.supplier,
			built.products,
			readProductOverrides(resolve(ROOT, `src/data/product-overrides.${source.supplier}.json`)),
		);
		if (report.named + report.coloured + report.merged > 0) {
			console.log(
				`[${source.supplier}] ${report.named} product(s) named, ${report.coloured} coloured, ${report.merged} merged into an existing colourway`,
			);
		}
		for (const code of report.unknownColourCodes) warnings.push(`unknown colour code ${code}`);
		for (const styleCode of report.unmatchedOverrides) warnings.push(`product override for unknown style ${styleCode}`);
		// Manual image fixes (src/data/image-overrides.<supplier>.json) win over the export.
		const overrides = readImageOverrides(resolve(ROOT, `src/data/image-overrides.${source.supplier}.json`));
		const { changed, unknown } = applyImageOverrides(products, overrides);
		if (changed > 0) console.log(`[${source.supplier}] ${changed} image override(s) applied`);
		for (const id of unknown) warnings.push(`image override for unknown product id ${id}`);
		for (const warning of warnings) {
			console.warn(`[${source.supplier}] ${warning}`);
		}
		const outPath = writeCatalog(source.supplier, products);
		console.log(`[${source.supplier}] ${summary} → ${outPath}`);
		totalProducts += products.length;
		totalWarnings += warnings.length;
	}

	console.log(`Done: ${totalProducts} products written, ${totalWarnings} warnings.`);
}

main();
